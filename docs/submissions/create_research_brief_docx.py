# --- 2. The Problem ---
doc.add_heading('2. The Problem', level=1)

doc.add_paragraph(
    'Earlier distractor-generation work produced MCQs that were either trivially easy (100% consensus correct) or '
    'confidently wrong (auditors agree on the wrong answer). The root cause was a corpus-based fallback sampler: '
    'when NLI paraphrase or correct-meaning-leak filters rejected a model-generated distractor, the pipeline sampled '
    'a fallback from other proverbs\' meanings — often generic moral statements or culturally mismatched idioms. '
    'Those fallbacks were plausible enough to attract auditor consensus, but wrong.'
)

doc.add_paragraph(
    'Key insight: You cannot trust distractors unless the fallback sampler is replaced or its output is filtered '
    'as aggressively as generator outputs. Our design applies the same filter stack to both.'
)

